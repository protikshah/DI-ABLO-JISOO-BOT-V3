module.exports = {
  config: {
    name: "treasure",
    aliases: ["tre", "ts "],
    version: "1.3.0",
    author: "Pratik Shah",
    countDown: 20,
    role: 0,
    shortDescription: "Solve Mini Detective Crime Cases (Reward: $100B / Fine: $20B)",
    category: "game",
    guide: {
      en: "{p}detective\nReply with option letter (A, B, or C) to solve the case!"
    }
  },

  formatMoney: function (num) {
    if (num >= 1000000000) return (num / 1000000000).toFixed(1).replace(/\.0$/, "") + "ʙ";
    if (num >= 1000000) return (num / 1000000).toFixed(1).replace(/\.0$/, "") + "ᴍ";
    if (num >= 1000) return (num / 1000).toFixed(1).replace(/\.0$/, "") + "ᴋ";
    return num.toLocaleString();
  },

  checkLimit: function (userID) {
    const now = Date.now();
    const FIVE_HOURS = 5 * 60 * 60 * 1000;
    let userData = global.treasureGames.cooldowns.get(userID);

    if (!userData || (now - userData.startTime > FIVE_HOURS)) {
      userData = { count: 0, startTime: now };
    }

    if (userData.count >= 25) {
      const remainingTime = Math.ceil((FIVE_HOURS - (now - userData.startTime)) / (60 * 1000));
      return { allowed: false, remainingTime };
    }

    return { allowed: true, userData };
  },

  onStart: async function ({ api, event, message }) {
    const sendMsg = (txt) => message && typeof message.reply === "function" ? message.reply(txt) : api.sendMessage(txt, event.threadID, event.messageID);
    const { senderID } = event;

    try {
      const limitInfo = this.checkLimit(senderID);
      if (!limitInfo.allowed) {
        return sendMsg(`❌ ʟɪᴍɪᴛ ʀᴇᴀᴄʜᴇᴅ!\n⏱️ ʏᴏᴜ ʜᴀᴠᴇ played 25/25 ʜᴜɴᴛs.\n💡 ᴘʟᴇᴀsᴇ ᴡᴀɪᴛ ${limitInfo.remainingTime} ᴍɪɴᴜᴛᴇs.`);
      }

      let user = await BankUser.findOne({ userID: senderID });
      if (!user) await BankUser.create({ userID: senderID, balance: 1000 });

      const selectedMap = MAPS[Math.floor(Math.random() * MAPS.length)];
      const currentStage = selectedMap.stages[0];

      let msgText = `🗺️ ───[ ${selectedMap.title} ]─── 🗺️\n\n`;
      msgText += `🚩 [ ʟᴇᴠᴇʟ 1/3 ]\n`;
      msgText += `📖 ${currentStage.story}\n\n`;
      msgText += `⚙️ ᴏᴘᴛɪᴏɴs :\n`;
      for (const [key, val] of Object.entries(currentStage.options)) {
        msgText += ` [${key}] ${val}\n`;
      }
      msgText += `\n💡 ʀᴇᴘʟʏ ᴡɪᴛʜ A, B, ᴏʀ C ᴛᴏ ᴄʜᴏᴏsᴇ!\n🏆 ғɪɴᴀʟ ᴛʀᴇᴀsᴜʀᴇ : $150ʙ | 💸 ᴛʀᴀᴘ ғɪɴᴇ : $30ʙ`;

      const res = await message.reply(msgText);

      if (global.GoatBot && global.GoatBot.onReply) {
        global.GoatBot.onReply.set(res.messageID, {
          commandName: this.config.name,
          messageID: res.messageID,
          author: senderID,
          mapData: selectedMap,
          stageIndex: 0,
          userData: limitInfo.userData
        });
      }

    } catch (err) {
      console.error("Treasure Hunt Error:", err);
      return sendMsg("❌ ᴛʀᴇᴀsᴜʀᴇ ʜᴜɴᴛ ɢᴀᴍᴇ ᴇʀʀᴏʀ!");
    }
  },

  onReply: async function ({ api, event, message, Reply }) {
    const sendMsg = (txt) => message && typeof message.reply === "function" ? message.reply(txt) : api.sendMessage(txt, event.threadID, event.messageID);
    const { senderID, body } = event;

    if (!Reply || Reply.author !== senderID) {
      return sendMsg("❌ ᴛʜɪs ɪs ɴᴏᴛ ʏᴏᴜʀ ʜᴜɴᴛ! sᴛᴀʀᴛ ʏᴏᴜʀ ᴏᴡɴ ᴡɪᴛʜ #treasure");
    }

    const userAns = (body || "").toUpperCase().trim();
    if (!["A", "B", "C"].includes(userAns)) {
      return sendMsg("❌ ɪɴᴠᴀʟɪᴅ ᴏᴘᴛɪᴏɴ! ᴘʟᴇᴀsᴇ ʀᴇᴘʟʏ ᴡɪᴛʜ A, B, ᴏʀ C.");
    }

    if (global.GoatBot && global.GoatBot.onReply) {
      global.GoatBot.onReply.delete(Reply.messageID);
    }

    try {
      const map = Reply.mapData;
      const currentStageIndex = Reply.stageIndex;
      const currentStage = map.stages[currentStageIndex];

      const isCorrect = userAns === currentStage.correct;
      const BANK_NAME = "🏛️ ᴅɪ-ᴀʙʟᴏ ᴊɪ-sᴏᴏ ʀᴏʏᴀʟ ᴠᴀᴜʟᴛ 🏛️";

      if (!isCorrect) {
        // Trap Triggered!
        let user = await BankUser.findOne({ userID: senderID });
        const FINE = 30000000000; // $30B
        user.balance = Math.max(0, user.balance - FINE);
        await user.save();

        Reply.userData.count += 1;
        global.treasureGames.cooldowns.set(senderID, Reply.userData);

        return sendMsg(
          `💥 ───[ ᴛʀᴀᴘ ᴛʀɪɢɢᴇʀᴇᴅ! ]─── 💥\n\n` +
          `💀 ʏᴏᴜ ᴄʜᴏsᴇ ᴛʜᴇ ᴡʀᴏɴɢ ᴘᴀᴛʜ ᴀɴᴅ ғᴇʟʟ ɪɴᴛᴏ ᴀ ᴛʀᴀᴘ!\n` +
          `💡 ᴄᴏʀʀᴇᴄᴛ ᴘᴀᴛʜ : Option [${currentStage.correct}]\n` +
          `📝 ʀᴇᴀsᴏɴ : ${currentStage.reason}\n\n` +
          `💸 ғɪɴᴇ : -$${this.formatMoney(FINE)}\n` +
          `💳 ʙᴀʟᴀɴᴄᴇ : $${user.balance.toLocaleString()}\n` +
          `🏦 ʙᴀɴᴋ : ${BANK_NAME}`
        );
      }

      // Check if there is a next stage
      if (currentStageIndex + 1 < map.stages.length) {
        const nextStageIndex = currentStageIndex + 1;
        const nextStage = map.stages[nextStageIndex];

        let msgText = `✨ ───[ 🎯 Correct Choice! ]─── ✨\n\n`;
        msgText += `🚩 [ ʟᴇᴠᴇʟ ${nextStageIndex + 1}/3 ]\n`;
        msgText += `📖 ${nextStage.story}\n\n`;
        msgText += `⚙️ ᴏᴘᴛɪᴏɴs :\n`;
        for (const [key, val] of Object.entries(nextStage.options)) {
          msgText += ` [${key}] ${val}\n`;
        }
        msgText += `\n💡 ʀᴇᴘʟʏ ᴡɪᴛʜ A, B, ᴏʀ C!`;

        const res = await message.reply(msgText);

        if (global.GoatBot && global.GoatBot.onReply) {
          global.GoatBot.onReply.set(res.messageID, {
            commandName: this.config.name,
            messageID: res.messageID,
            author: senderID,
            mapData: map,
            stageIndex: nextStageIndex,
            userData: Reply.userData
          });
        }
      } else {
        // Treasure Claimed!
        let user = await BankUser.findOne({ userID: senderID });
        const REWARD = 150000000000; // $150B
        user.balance += REWARD;
        await user.save();

        Reply.userData.count += 1;
        global.treasureGames.cooldowns.set(senderID, Reply.userData);

        return sendMsg(
          `💎 ───[ ᴛʀᴇᴀsᴜʀᴇ ᴜɴʟᴏᴄᴋᴇᴅ! ]─── 💎\n\n` +
          `👑 ᴄᴏɴɢʀᴀᴛᴜʟᴀᴛɪᴏɴs! ʏᴏᴜ sᴜᴄᴄᴇssғᴜʟʟʏ ᴄʟᴇᴀʀᴇᴅ ᴀʟʟ 3 sᴛᴀɢᴇs!\n` +
          `💡 ʀᴇᴀsᴏɴ : ${currentStage.reason}\n\n` +
          `🏆 ᴛʀᴇᴀsᴜʀᴇ ʀᴇᴡᴀʀᴅ : +$${this.formatMoney(REWARD)}\n` +
          `💳 ʙᴀʟᴀɴᴄᴇ : $${user.balance.toLocaleString()}\n` +
          `🏦 ʙᴀɴᴋ : ${BANK_NAME}`
        );
      }

    } catch (err) {
      console.error("Treasure Reply Error:", err);
      return sendMsg("❌ ᴇʀʀᴏʀ ᴘʀᴏᴄᴇssɪɴɢ ʏᴏᴜʀ ʜᴜɴᴛ!");
    }
  }
};